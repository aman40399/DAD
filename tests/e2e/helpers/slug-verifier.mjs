export function isUrlSafeSlug(slug) {
  // Only lowercase alphanumeric and single hyphens, no leading/trailing hyphens
  return /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)
}

export function referenceSlugify(title) {
  if (!title || typeof title !== 'string') return ''
  let text = title.trim()

  const hasHindi = /[\u0900-\u097F]/.test(text)
  if (hasHindi) {
    for (const [hindi, latin] of Object.entries(HINDI_CHAR_MAP)) {
      text = text.replace(new RegExp(hindi, 'g'), latin)
    }
  }

  return text
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .trim()
}
